"""VisionParams — the fully-free parameter surface, and the Vision Mark-32 tables.

Vision (Aly-Ashur-Ben-Sasson-Dhooghe-Szepieniec, "Design of Symmetric-Key
Primitives for Advanced Cryptographic Protocols", IACR ToSC 2020(3),
https://eprint.iacr.org/2019/426, Section 5) is a generator over a binary field
F_{2^n}, a state width m, a linearized affine polynomial B, an MDS matrix, and a
round-constant schedule — no enumerated member list — so, like Poseidon2, the
parameterization is one value-compared object and `Vision(params)` takes it
whole (docs/reference/conventions.md, "a parameter per choice").

The core treats `dtype` as opaque: any dtype whose `*` is the field
multiplication and whose `x ** -1` is the field inverse with `0 ** -1 == 0`
satisfies it. The round-key surface is the EXPANDED zero-key schedule — the
2N+1 step keys the paper derives by feeding the key schedule the all-zero
master key — rather than the (initial_constant, constants_matrix,
constants_constant) triple that generates them: the permutation reads only the
step keys, and the generator recurrence is pinned in
`testing/reference_test.py` against the triple instead.

`vision_mark32_params` is the shipped 128-bit instance, Vision Mark-32
(Ashur-Mahzoun-Posen-Šijačić, "Vision Mark-32: ZK-Friendly Hash Function Over
Binary Tower Fields", https://eprint.iacr.org/2024/633): n = 32 over the
Fan-Paar tower GF(2^32), m = 24 (rate 16 / capacity 8), N = 8 rounds. Note the
round count follows Mark-32's re-derived attack bounds (its Section 4,
Table 1), NOT the ToSC 2020 paper's `N = 2*max(l0, l1, 5) >= 10` floor — the
two instances in the original paper's Appendix D are 10-round.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import frx.numpy as fnp
import numpy as np
from frx import Array


@dataclass(frozen=True)
class VisionParams:
    """Fully-free parameter surface of a Vision permutation.

    The affine polynomials are stored constant-first: ``b[0]`` is the affine
    constant and ``b[1 + j]`` the coefficient of ``x**(2**j)`` — the order the
    paper writes ``B(x) = b_{-1} + sum_i b_i x^{2^i}`` in (its Section 4.1).
    The KULeuven-COSIC reference stores the same order; binius-models stores
    the constant LAST, so a table taken from there is rotated by one.

    Contract (validated in __post_init__):
      rounds : N >= 1; the permutation runs 2N steps.
      b : (>= 2,) over dtype; the degree-4 recommendation of the paper is
          b of length 4 (constant + coefficients of x, x^2, x^4).
      b_inv : (>= 2,) over dtype; B's compositional inverse, dense by
          construction (n + 1 entries over F_{2^n}). The core cannot verify
          the inverse relation (it does not evaluate polynomials eagerly);
          `testing/reference_test.py` pins it for the shipped instance.
      mds : (width, width) over dtype; applied as `mds @ state`.
      round_keys : (2*rounds + 1, width) over dtype; the step keys
          K_0..K_{2N}, K_0 injected before round 1.
    """

    width: int
    dtype: Any
    rounds: int
    b: Array
    b_inv: Array
    mds: Array
    round_keys: Array

    def __post_init__(self) -> None:
        if self.rounds < 1:
            raise ValueError(f"rounds must be a positive int, got {self.rounds}")
        w = self.width
        for name in ("b", "b_inv"):
            arr = getattr(self, name)
            got = tuple(np.shape(arr))
            if len(got) != 1 or got[0] < 2:
                raise ValueError(
                    f"{name}: expected a 1-D constant-plus-coefficients vector of "
                    f"length >= 2, got shape {got}"
                )
        checks = {
            "mds": ((w, w), self.mds),
            "round_keys": ((2 * self.rounds + 1, w), self.round_keys),
        }
        for name, (want, arr) in checks.items():
            got = tuple(np.shape(arr))
            if got != want:
                raise ValueError(f"{name}: expected shape {want}, got {got}")
        for name in ("b", "b_inv", "mds", "round_keys"):
            arr = getattr(self, name)
            if arr.dtype != self.dtype:
                raise ValueError(
                    f"{name}: expected dtype {self.dtype}, got {arr.dtype}"
                )

    # Value equality/hash: a permutation rides pytree aux, which must compare
    # by value — identity equality re-traces the enclosing jit zone per freshly
    # built instance (docs/reference/conventions.md "Pytree registration"). The
    # dataclass-derived __eq__ is unusable anyway: `==` on the Array fields is
    # elementwise. One cached host-side key serves both methods, as
    # `Poseidon2Params` lays out (jit dispatch calls __eq__ per call, so a live
    # device-array comparison there would sync per dispatch).
    _ARRAY_FIELDS = ("b", "b_inv", "mds", "round_keys")

    def _value_key(self) -> tuple:
        k = self.__dict__.get("_key")
        if k is None:
            k = (self.width, self.dtype, self.rounds) + tuple(
                np.asarray(getattr(self, f)).tobytes() for f in self._ARRAY_FIELDS
            )
            object.__setattr__(self, "_key", k)
        return k

    def __eq__(self, other: object) -> bool:
        if self is other:
            return True
        if not isinstance(other, VisionParams):
            return NotImplemented
        return self._value_key() == other._value_key()

    def __hash__(self) -> int:
        # Memoized like `_key`: the permute jit zone hashes the params on every
        # dispatch, and CPython caches neither tuple nor bytes hashes, so a
        # bare hash(key) would re-SipHash the table bytes per permute call.
        h = self.__dict__.get("_hash")
        if h is None:
            h = hash(self._value_key())
            object.__setattr__(self, "_hash", h)
        return h


def vision_mark32_params(dtype: Any) -> VisionParams:
    """The Vision Mark-32 instance over `dtype` — the shipped 128-bit member.

    `dtype` must be the Fan-Paar tower GF(2^32) — `zk_dtypes.binary_field_t5`,
    whose tower is byte-compatible with Binius' `BinaryField32b`
    (zk_dtypes/include/field/binary_field_config.h) — for the tables below to
    mean what Mark-32 means; it is a parameter only because the core names no
    dtype package (the same field could be registered elsewhere). Taking a
    different field here would be a different (unanalyzed) hash, which is why
    the tables are not parameters of this factory.

    m = 24 state elements (rate 16 / capacity 8), N = 8 rounds, per the Vision
    Mark-32 paper (https://eprint.iacr.org/2024/633, Section 3, Algorithm 1).
    """
    return VisionParams(
        width=24,
        dtype=dtype,
        rounds=8,
        b=fnp.array(_B, dtype=dtype),
        b_inv=fnp.array(_B_INV, dtype=dtype),
        mds=fnp.array(_MDS, dtype=dtype),
        round_keys=fnp.array(_ROUND_KEYS, dtype=dtype),
    )


